def update_ts(filepath, trans_dict):
    tree = ET.parse(filepath)
    root = tree.getroot()
    count = 0
    missing = []
    for context in root.findall('context'):
        for msg in context.findall('message'):
            src = msg.find('source').text
            trans = msg.find('translation')
            if src in trans_dict:
                trans.text = trans_dict[src]
                if 'type' in trans.attrib:
                    del trans.attrib['type']
                count += 1
            else:
                missing.append(src)
    if missing:
        print('MISSING for', filepath, missing)
    tree.write(filepath, encoding='utf-8', xml_declaration=True)
    print(f'Updated {filepath}: {count} translations applied.')

